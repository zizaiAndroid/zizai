#!/usr/bin/env python3
"""
Generates Zizai's branding overlay (docs/IMPLEMENTATION_PLAN.md P0-06).

Upstream's strings name the product "Dictate" in about 150 English and 100 Simplified Chinese strings, plus
upstream links in strings_dont_translate.xml. Editing those files would conflict on every upstream sync, so
this script writes overriding copies into app/src/zizai/res/, a resource directory that app/build.gradle.kts
attaches to every build type. Build-type resources outrank app/src/main/res, so the overrides win without a
single upstream line changing.

Run it again after every upstream sync (docs/IMPLEMENTATION_PLAN.md §6.1); commit the result:

    python tools/zizai/branding.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAIN_RES = ROOT / "app" / "src" / "main" / "res"
OUT_RES = ROOT / "app" / "src" / "zizai" / "res"
OUT_NAME = "strings_zizai_branding.xml"

REPO = "https://github.com/zizaiAndroid/zizai"

# Strings where "Dictate" is the verb, not the product, or which only describe a feature that is switched
# off in v1 (Dictate Cloud). They keep upstream's wording.
EN_KEEP = {
    "quick_action__ime_ui_mode_dictate",  # the mic action: "Dictate"
    "setup__floating_button__title",  # "Dictate anywhere (optional)"
    "apptour52__intro_title",  # "Dictate everywhere"
    "dictate__cloud_intro_title",  # "Dictate without an API key"
    "dictate__cloud_activate_btn",  # "Dictate through Dictate Cloud"
}

# Exact values, applied after the brand substitution.
EN_OVERRIDES = {
    "app_name": "Zizai",
    "app_name_full": "Zizai Keyboard",
    "about__made_by": "Based on Dictate Keyboard by DevEmperor,\\na fork of FlorisBoard",
    # Placeholder until the zizai.io domain (P0-01) has a mailbox.
    "about__feedback__email": "feedback@zizai.io",
    "florisboard__repo_url": REPO,
    "florisboard__website_url": REPO,
    "florisboard__issue_tracker_url": f"{REPO}/issues",
    "florisboard__privacy_policy_url": f"{REPO}/blob/main/docs/privacy.md",
    "florisboard__changelog_url": f"{REPO}/releases",
    "florisboard__commit_by_hash_url": f"{REPO}/commit/{{hash}}",
    "florisboard__spell_checker_wiki_url": REPO,
    "florisboard__theme_editor_wiki_url": REPO,
    "florisboard__internal_key_codes_url":
        f"{REPO}/blob/main/app/src/main/kotlin/dev/patrickgold/florisboard/ime/text/key/KeyCode.kt",
}

ZH_HANS_OVERRIDES = {"app_name": "字在", "app_name_full": "字在输入法"}
ZH_HANT_OVERRIDES = {"app_name": "字在", "app_name_full": "字在輸入法"}

STRING_RE = re.compile(r'(<string\s+name="([^"]+)"[^>]*>)(.*?)(</string>)', re.DOTALL)
SELF_CLOSING_RE = re.compile(r'<string\s+name="([^"]+)"[^>]*/>')


def read_strings(*files):
    """name -> (open_tag, text) for every <string> in the given files that exist."""
    found = {}
    for f in files:
        if f.exists():
            for m in STRING_RE.finditer(f.read_text(encoding="utf-8")):
                found[m.group(2)] = (m.group(1), m.group(3))
    return found


CJK = "　-〿㐀-鿿＀-￯"


def brand(text, keyboard_name, name):
    text = text.replace("Dictate Keyboard", keyboard_name)
    text = re.sub(r"\bDictate\b", name, text)
    if re.search(f"[{CJK}]", name):
        # Upstream's Chinese puts spaces around the Latin "Dictate"; next to Chinese text they now look
        # wrong ("离开 字在 即可"), so drop a space wherever it sits between the name and Chinese.
        text = re.sub(f"(?<=[{CJK}]) (?={re.escape(name)})", "", text)
        text = re.sub(f"(?<={re.escape(name)}) (?=[{CJK}])", "", text)
    return text


def overlay(strings, keyboard_name, name, keep, overrides):
    out = {}
    for key, (tag, text) in strings.items():
        if key not in keep and "Dictate" in text:
            out[key] = (tag, brand(text, keyboard_name, name))
    for key, value in overrides.items():
        tag = strings.get(key, (f'<string name="{key}">', ""))[0]
        out[key] = (tag, value)
    return out


def write(qualifier, entries):
    folder = OUT_RES / qualifier
    folder.mkdir(parents=True, exist_ok=True)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by tools/zizai/branding.py from upstream's strings. Do not edit by hand. -->",
        '<resources xmlns:tools="http://schemas.android.com/tools"'
        ' tools:ignore="ExtraTranslation,MissingTranslation,UnusedResources">',
    ]
    for key in sorted(entries):
        tag, text = entries[key]
        lines.append(f"    {tag}{text}</string>")
    lines.append("</resources>")
    (folder / OUT_NAME).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return len(entries)


def main():
    en = read_strings(MAIN_RES / "values" / "strings.xml", MAIN_RES / "values" / "strings_dont_translate.xml")
    zh_cn = read_strings(MAIN_RES / "values-zh-rCN" / "strings.xml")
    if not en:
        sys.exit("no upstream strings found; run from the repository")
    counts = {
        "values": write("values", overlay(en, "Zizai Keyboard", "Zizai", EN_KEEP, EN_OVERRIDES)),
        "values-zh-rCN": write("values-zh-rCN", overlay(zh_cn, "字在输入法", "字在", set(), ZH_HANS_OVERRIDES)),
        "values-zh-rTW": write("values-zh-rTW", overlay({}, "", "", set(), ZH_HANT_OVERRIDES)),
        "values-zh-rHK": write("values-zh-rHK", overlay({}, "", "", set(), ZH_HANT_OVERRIDES)),
    }
    for qualifier, n in counts.items():
        print(f"{qualifier}: {n} strings")


if __name__ == "__main__":
    main()
